// Builds the season table (`apps/web/app/lib/fx/hko_table.ts`) and its test vector
// (`apps/web/app/lib/__tests__/fixtures/fx_hko.json`) from the Hong Kong Observatory's
// Gregorian-Lunar conversion tables
// (https://www.hko.gov.hk/en/gts/time/calendar/text/files/T<year>e.txt), downloaded beforehand
// into one directory. Run by hand to extend the table; the app never fetches anything.
//   bun scripts/fx/gen_hko.ts <dir with T2024e.txt, T2025e.txt, ...>
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const LIB = join(import.meta.dir, '../../apps/web/app/lib')
export const TABLE = join(LIB, 'fx/hko_table.ts')
export const VECTOR = join(LIB, '__tests__/fixtures/fx_hko.json')

export interface MonthStart {
  day: string
  month: number
  // A leap month carries the name of the month before it.
  leap: boolean
}

export interface Year {
  months: MonthStart[]
  terms: Record<string, string>
}

const ROW = /^(\d{4})\/(\d{1,2})\/(\d{1,2})\s+(.*?)\s{2,}\S+day\s*(.*)$/
const MONTH = /^(\d{1,2})(?:st|nd|rd|th) Lunar Month$/
const TERMS = ['Vernal Equinox', 'Summer Solstice', 'Autumnal Equinox', 'Winter Solstice']

const iso = (y: string, m: string, d: string) => `${y}-${m.padStart(2, '0')}-${d.padStart(2, '0')}`
const plus = (day: string, days: number) => {
  const t = new Date(`${day}T00:00:00Z`)
  t.setUTCDate(t.getUTCDate() + days)
  return t.toISOString().slice(0, 10)
}

export function parseYear(text: string): Year {
  const months: MonthStart[] = []
  const terms: Record<string, string> = {}
  for (const line of text.split(/\r?\n/)) {
    const row = ROW.exec(line.trim())
    if (!row) continue
    const [, y, m, d, lunar, term] = row
    const day = iso(y, m, d)
    const month = MONTH.exec(lunar.trim())
    if (month) {
      const n = Number(month[1])
      months.push({ day, month: n, leap: months[months.length - 1]?.month === n })
    }
    if (TERMS.includes(term.trim())) terms[term.trim()] = day
  }
  return { months, terms }
}

export interface Built {
  first: number
  last: number
  lunarNewYear: Record<number, string>
  midAutumn: Record<number, string>
  monthStarts: string[]
  terms: Record<string, string>
}

export function build(tables: Record<number, string>): Built {
  const years = Object.keys(tables)
    .map(Number)
    .sort((a, b) => a - b)
  if (!years.length) throw new Error('no tables')
  const first = years[0]
  const last = years[years.length - 1]
  const lunarNewYear: Record<number, string> = {}
  const midAutumn: Record<number, string> = {}
  const monthStarts: string[] = []
  const terms: Record<string, string> = {}
  for (let y = first; y <= last; y++) {
    if (tables[y] === undefined) throw new Error(`no table for ${y}`)
    const year = parseYear(tables[y])
    const start = (month: number) =>
      year.months.find(m => m.month === month && !m.leap && m.day.startsWith(`${y}-`))?.day
    const newYear = start(1)
    const eighth = start(8)
    if (!newYear || !eighth) throw new Error(`the table for ${y} has no 1st or 8th lunar month`)
    lunarNewYear[y] = newYear
    midAutumn[y] = plus(eighth, 14)
    monthStarts.push(...year.months.map(m => m.day))
    for (const [name, day] of Object.entries(year.terms)) terms[`${y} ${name}`] = day
  }
  return {
    first,
    last,
    lunarNewYear,
    midAutumn,
    monthStarts: [...new Set(monthStarts)].sort(),
    terms,
  }
}

const record = (name: string, days: Record<number, string>) =>
  `export const ${name}: Record<number, string> = {\n${Object.keys(days)
    .map(Number)
    .sort((a, b) => a - b)
    .map(y => `  '${y}': '${days[y]}',\n`)
    .join('')}}\n`

export const tableText = (t: Pick<Built, 'first' | 'last' | 'lunarNewYear' | 'midAutumn'>) =>
  `// Generated by scripts/fx/gen_hko.ts from the Hong Kong Observatory's Gregorian-Lunar conversion\n` +
  `// tables ${t.first}-${t.last}. Dates are civil dates in China (UTC+8).\n` +
  `export const HKO_FIRST = ${t.first}\n` +
  `export const HKO_LAST = ${t.last}\n` +
  record('LUNAR_NEW_YEAR', t.lunarNewYear) +
  record('MID_AUTUMN', t.midAutumn)

export const vectorText = (v: Pick<Built, 'monthStarts' | 'terms'>) =>
  `${JSON.stringify({ monthStarts: v.monthStarts, terms: v.terms }, null, 2)}\n`

export function readTables(dir: string) {
  const tables: Record<number, string> = {}
  for (const name of readdirSync(dir)) {
    const year = /^T(\d{4})e\.txt$/.exec(name)
    if (year) tables[Number(year[1])] = readFileSync(join(dir, name), 'latin1')
  }
  return tables
}

function main(args: string[]) {
  const [dir] = args
  if (!dir) {
    console.error('usage: bun scripts/fx/gen_hko.ts <dir with T<year>e.txt files>')
    process.exit(2)
  }
  const built = build(readTables(dir))
  writeFileSync(TABLE, tableText(built))
  writeFileSync(VECTOR, vectorText(built))
  console.log(
    `${built.first}-${built.last}: ${built.monthStarts.length} month starts, ${Object.keys(built.terms).length} terms`
  )
}

if (import.meta.main) main(process.argv.slice(2))
