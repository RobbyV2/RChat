//! The look-alike fold: one non-Latin letter to one Latin letter, never the other way round.

use crate::fold_table::FOLD;
use std::collections::BTreeMap;
use unicode_normalization::UnicodeNormalization;
use unicode_normalization::char::is_combining_mark;
use unicode_security::mixed_script::AugmentedScriptSet;

/// The table: sources sorted, each a lowercase non-Latin letter that normalization keeps.
pub fn table() -> &'static [(char, char)] {
    FOLD
}

/// The Latin letter `c` passes for, or `c` itself.
pub fn fold(c: char) -> char {
    match FOLD.binary_search_by_key(&c, |&(from, _)| from) {
        Ok(i) => FOLD[i].1,
        Err(_) => c,
    }
}

/// Whether `c` is of the Latin script or of one every script shares (digits, signs, marks).
pub fn latin_or_shared(c: char) -> bool {
    let mut scripts = AugmentedScriptSet::for_char(c);
    scripts.intersect_with(AugmentedScriptSet::for_char('a'));
    !scripts.is_empty()
}

/// The Unicode version a `confusables.txt` names in its header.
pub fn version(confusables: &str) -> &str {
    confusables
        .lines()
        .find_map(|l| l.strip_prefix("# Version: "))
        .map_or("", str::trim)
}

fn one(field: &str) -> Option<char> {
    let mut points = field.split_whitespace();
    let c = u32::from_str_radix(points.next()?, 16).ok()?;
    match points.next() {
        None => char::from_u32(c),
        Some(_) => None,
    }
}

fn lowered(c: char) -> Option<char> {
    let mut lower = c.to_lowercase();
    match (lower.next(), lower.next()) {
        (Some(l), None) => Some(l),
        _ => None,
    }
}

fn kept(c: char) -> bool {
    c.is_alphabetic()
        && !c.is_numeric()
        && !is_combining_mark(c)
        && !latin_or_shared(c)
        && lowered(c) == Some(c)
        && c.nfkc().eq([c])
}

/// The table a `confusables.txt` gives: every single non-Latin letter whose look-alike is one
/// ASCII letter, and the lowercase of every such capital. A letter's own look-alike wins over
/// its capital's; among capitals the smallest wins.
pub fn derive(confusables: &str) -> Vec<(char, char)> {
    let mut own: BTreeMap<char, char> = BTreeMap::new();
    let mut capitals: BTreeMap<char, (char, char)> = BTreeMap::new();
    for line in confusables.lines() {
        let mut fields = line.split('#').next().unwrap_or("").split(';');
        let (Some(from), Some(to)) = (fields.next().and_then(one), fields.next().and_then(one))
        else {
            continue;
        };
        if !to.is_ascii_alphabetic() {
            continue;
        }
        let to = to.to_ascii_lowercase();
        if kept(from) {
            own.insert(from, to);
        }
        if let Some(lower) = lowered(from).filter(|&l| l != from && kept(l)) {
            let best = capitals.entry(lower).or_insert((from, to));
            if from < best.0 {
                *best = (from, to);
            }
        }
    }
    let mut table: BTreeMap<char, char> =
        capitals.into_iter().map(|(l, (_, to))| (l, to)).collect();
    table.extend(own);
    table.into_iter().collect()
}

/// The text of `src/fold_table.rs` for a table.
pub fn render(table: &[(char, char)], version: &str) -> String {
    let mut out = format!(
        "// Generated by tools/gen_fold.rs from tools/confusables.txt (Unicode {version}). Do not edit.\n\npub(crate) static FOLD: &[(char, char)] = &[\n"
    );
    for (from, to) in table {
        out.push_str(&format!("    ('\\u{{{:x}}}', '{to}'),\n", u32::from(*from)));
    }
    out.push_str("];\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use unicode_normalization::UnicodeNormalization;

    const PINNED: &str = include_str!("../tools/confusables.txt");

    #[test]
    fn the_checked_in_table_is_what_the_pinned_file_gives() {
        assert_eq!(version(PINNED), "16.0.0");
        assert_eq!(
            (
                unicode_security::UNICODE_VERSION.0,
                unicode_security::UNICODE_VERSION.1
            ),
            (16, 0)
        );
        let derived = derive(PINNED);
        assert_eq!(table(), derived.as_slice());
        assert_eq!(
            include_str!("fold_table.rs"),
            render(&derived, version(PINNED)),
            "run the gen_fold example"
        );
        assert!(table().len() > 100);
    }

    #[test]
    fn every_source_is_one_non_latin_letter_and_every_target_one_latin_letter() {
        for pair in table().windows(2) {
            assert!(pair[0].0 < pair[1].0, "sorted, no source twice");
        }
        for &(from, to) in table() {
            assert!(to.is_ascii_lowercase(), "{from:?} -> {to:?}");
            assert!(from.is_alphabetic() && !from.is_numeric(), "{from:?}");
            assert!(!is_combining_mark(from), "{from:?}");
            assert!(!latin_or_shared(from), "{from:?}");
            assert_eq!(from.to_lowercase().collect::<String>(), from.to_string());
            assert_eq!(
                from.to_string().nfkc().collect::<String>(),
                from.to_string()
            );
        }
    }

    #[test]
    fn latin_letters_digits_and_signs_never_fold() {
        for c in ('\0'..='\u{24f}').chain(['ı', 'ſ', 'ǀ', 'ｍ', 'ℓ', '𝐚', '０', '١', '|', '∣'])
        {
            assert_eq!(fold(c), c, "{c:?}");
        }
        assert!(latin_or_shared('m'));
        assert!(latin_or_shared('1'));
        assert!(latin_or_shared('ǀ'));
        assert!(!latin_or_shared('м'));
    }

    #[test]
    fn cyrillic_and_greek_look_alikes_fold_to_their_latin_letters() {
        let pairs = [
            ('а', 'a'),
            ('в', 'b'),
            ('е', 'e'),
            ('к', 'k'),
            ('м', 'm'),
            ('н', 'h'),
            ('о', 'o'),
            ('р', 'p'),
            ('с', 'c'),
            ('т', 't'),
            ('у', 'y'),
            ('х', 'x'),
            ('і', 'i'),
            ('ј', 'j'),
            ('ѕ', 's'),
            ('ԁ', 'd'),
            ('α', 'a'),
            ('β', 'b'),
            ('ε', 'e'),
            ('ι', 'i'),
            ('κ', 'k'),
            ('ν', 'v'),
            ('ο', 'o'),
            ('ρ', 'p'),
            ('τ', 't'),
            ('υ', 'u'),
            ('χ', 'x'),
        ];
        for (from, to) in pairs {
            assert_eq!(fold(from), to, "{from}");
        }
        assert_eq!(fold('γ'), 'y');
        assert_eq!(fold('λ'), 'λ');
        assert_eq!(fold('ж'), 'ж');
        assert_eq!(fold('猫'), '猫');
    }

    #[test]
    fn a_letters_own_look_wins_over_its_capitals() {
        let source = "\
# Version: 9.9.9
03C5 ;\t0075 ;\tMA\t# upsilon looks like u
03A5 ;\t0059 ;\tMA\t# capital upsilon looks like Y
0412 ;\t0042 ;\tMA\t# capital ve looks like B
0417 ;\t0033 ;\tMA\t# capital ze looks like 3
0661 ;\t006C ;\tMA\t# a digit
0049 ;\t006C ;\tMA\t# Latin
0430 0301 ;\t0061 0301 ;\tMA\t# two code points
0432 ;\t0299 ;\tMA\t# not an ASCII letter
0D02 ;\t006F ;\tMA\t# a mark
";
        assert_eq!(version(source), "9.9.9");
        assert_eq!(derive(source), [('υ', 'u'), ('в', 'b')]);
        assert_eq!(
            render(&derive(source), "9.9.9"),
            "// Generated by tools/gen_fold.rs from tools/confusables.txt (Unicode 9.9.9). Do not edit.\n\npub(crate) static FOLD: &[(char, char)] = &[\n    ('\\u{3c5}', 'u'),\n    ('\\u{432}', 'b'),\n];\n"
        );
    }

    #[test]
    fn direct_entries_agree_with_the_pinned_security_tables() {
        let mut checked = 0;
        for &(from, to) in table() {
            let skeleton: String = unicode_security::skeleton(&from.to_string()).collect();
            let upper: String = from.to_uppercase().collect();
            let upper_skeleton: String = unicode_security::skeleton(&upper).collect();
            assert!(
                skeleton.eq_ignore_ascii_case(&to.to_string())
                    || upper_skeleton.eq_ignore_ascii_case(&to.to_string()),
                "{from:?} -> {to:?}: {skeleton:?} {upper_skeleton:?}"
            );
            checked += 1;
        }
        assert_eq!(checked, table().len());
    }
}
